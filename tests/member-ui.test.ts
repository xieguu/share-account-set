import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { fixture, until } from './helpers/runtime.js';

test('member UI creates private environments, shares and pauses them, imports JSON with consent and configures a local device', { timeout: 90_000 }, async t => {
  const f = await fixture(t);
  f.config.agentInsecureLoopback = true;
  const browser = await chromium.launch();
  t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage();
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(f.config.origin);
  await page.locator('#login-form [name=username]').fill('owner');
  await page.locator('#login-form [name=password]').fill('integration-member-password');
  await page.locator('#login-form [type=submit]').click();
  await page.locator('#workspace').waitFor({ state: 'visible' });
  assert.equal(await page.locator('[data-view=members]').isVisible(), false);
  async function form(name: string, mode: string) {
    await page.locator('#add-environment').click();
    await page.locator('#environment-form [name=mode]').selectOption(mode);
    await page.locator('#environment-form [name=name]').fill(name);
    await page.locator('#environment-form [name=startUrl]').fill(`${f.labOrigin}/`);
    await page.locator('#environment-form [name=allowedOrigins]').click();
    await page.locator('#environment-form [name=allowedOrigins]').fill(f.labOrigin);
  }
  await form('Owner created server', 'server');
  const response = page.waitForResponse(response => response.url().endsWith('/api/environments') && response.request().method() === 'POST');
  await page.locator('#environment-form [type=submit]').click();
  const result = await response;
  assert.equal(result.status(), 201, await result.text());
  await page.locator('#environment-dialog').waitFor({ state: 'hidden' });
  const card = page.locator('.environment-card').filter({ hasText: 'Owner created server' });
  await card.waitFor();
  const env = f.runtime.store.environments()[0]!;
  assert.equal(env.ownerId, f.ownerUser.id);
  await card.locator('[data-action=share-env]').click();
  await page.locator(`#environment-grants-list input[value="${f.guestUser.id}"]`).check();
  await until(() => f.runtime.store.hasAccess(f.guestUser, env.id), 'UI grant saved');
  await page.locator('#environment-grants-dialog .dialog-close').click();
  await card.locator('[data-action=pause-env]').click();
  await card.getByText('已暂停共享', { exact: true }).waitFor();
  assert.equal(await card.locator('[data-action=start]').isDisabled(), true);
  await card.locator('[data-action=pause-env]').click();
  await card.getByText('按需启动', { exact: true }).waitFor();
  await form('Imported via form', 'import');
  const state = { cookies: [], origins: [{ origin: f.labOrigin, localStorage: [{ name: 'ui-import', value: 'restored' }] }] };
  await page.locator('#storage-file').setInputFiles({ name: 'state.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(state)) });
  await page.locator('#storage-preview').getByText(/存储来源/).waitFor();
  await page.locator('#environment-form [type=submit]').click();
  assert.equal(await page.locator('#environment-dialog').isVisible(), true, 'consent blocks submission');
  assert.equal(f.runtime.store.environments().length, 1);
  await page.screenshot({ path: 'test-results/member-import.png', fullPage: true });
  await page.locator('#import-confirm').check();
  await page.locator('#environment-form [type=submit]').click();
  await page.locator('#environment-dialog').waitFor({ state: 'hidden' });
  assert.equal(f.runtime.store.environments().length, 2);
  await form('My local computer', 'local');
  assert.equal(await page.locator('#local-agent-help').isVisible(), true);
  await page.locator('#environment-form [type=submit]').click();
  await page.locator('#environment-dialog').waitFor({ state: 'hidden' });
  const device = page.locator('.environment-card').filter({ hasText: 'My local computer' });
  await device.getByText('本地设备离线', { exact: true }).waitFor();
  assert.equal(await device.locator('[data-action=start]').isDisabled(), true);
  page.once('dialog', dialog => dialog.accept());
  const download = page.waitForEvent('download');
  await device.locator('[data-action=pair-agent]').click();
  assert.match((await download).suggestedFilename(), /^relayhub-agent-[a-f\d]+\.json$/);
  await page.screenshot({ path: 'test-results/member-sharing.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/member-sharing-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
});
